// Generate standard storage grid locations STR1S1B1 to STR3S4B4 plus open shelves
export const generateLocations = (): StorageLocation[] => {
  const locs: StorageLocation[] = [];
  for (let r = 1; r <= 3; r++) {
    for (let s = 1; s <= 4; s++) {
      // Add open shelf slot (e.g. STR1S1)
      locs.push({
        code: `STR${r}S${s}`,
        rack: r,
        shelf: s,
        box: null,
        label: `Rack ${r}, Shelf ${s} (Open Reel Bay)`,
      });
      // Add 4 boxes per shelf
      for (let b = 1; b <= 4; b++) {
        locs.push({
          code: `STR${r}S${s}B${b}`,
          rack: r,
          shelf: s,
          box: b,
          label: `Rack ${r}, Shelf ${s}, Box ${b}`,
        });
      }
    }
  }
  return locs;
};

